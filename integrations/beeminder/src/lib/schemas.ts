import { createApiServiceError, isApiErrorRecord } from 'slates';
import { z } from 'zod';

export let goalSchema = z.object({
  slug: z.string().describe('URL-friendly name for the goal'),
  title: z.string().describe('Human-readable title'),
  goalType: z
    .string()
    .describe('Goal type (hustler, biker, fatloser, gainer, inboxer, drinker, custom)'),
  gunits: z.string().describe('Units for the goal'),
  goaldate: z.number().nullable().optional().describe('Unix timestamp of the goal end date'),
  goalval: z.number().nullable().optional().describe('Target value at the goal date'),
  rate: z
    .number()
    .nullable()
    .optional()
    .describe('Rate of change in the goal rate units (runits)'),
  curval: z.number().optional().describe('Current value on the bright red line'),
  curday: z.number().optional().describe('Current day as unix timestamp'),
  pledge: z.number().optional().describe('Current pledge amount in USD'),
  yaxis: z.string().optional().describe('Y-axis label'),
  safebuf: z.number().optional().describe('Number of safe days before derailment'),
  safesum: z.string().optional().describe('Human-readable summary of the safety buffer'),
  losedate: z
    .number()
    .optional()
    .describe('Unix timestamp when the goal will derail if no data is added'),
  limsum: z.string().optional().describe('Summary of how much is needed before the deadline'),
  deadline: z.number().optional().describe('Seconds after midnight for the goal deadline'),
  secret: z.boolean().optional().describe('Whether the goal is secret'),
  datapublic: z.boolean().optional().describe('Whether the data is public'),
  tags: z.array(z.string()).optional().describe('Tags associated with the goal'),
  updatedAt: z.number().optional().describe('Unix timestamp of last update'),
  burner: z.string().optional().describe('Whether the goal is on the front or back burner'),
  roadall: z
    .array(z.any())
    .optional()
    .describe('Full road matrix (bright red line specification)'),
  callbackUrl: z
    .string()
    .nullable()
    .optional()
    .describe('Webhook URL for derail notifications'),
  autodata: z.string().nullable().optional().describe('Automatic data source name'),
  won: z.boolean().optional().describe('Whether the goal has been won'),
  lane: z
    .number()
    .optional()
    .describe('Current lane position (1=red, 2=orange, 3=blue, 4=green)'),
  mathishard: z.array(z.number()).optional().describe('Summary of the road ahead'),
  headsum: z.string().optional().describe('Summary of the goal status'),
  lastDatapoint: z.any().optional().describe('Most recent datapoint'),
  integery: z.boolean().optional().describe('Whether the goal values are integers'),
  fineprint: z.string().nullable().optional().describe('Fine print for the goal'),
  todayta: z.boolean().optional().describe('Whether there is data for today'),
  hhmmformat: z.boolean().optional().describe('Whether values are in HH:MM format'),
  id: z.string().optional().describe('Unique goal identifier'),
  runits: z.string().optional().describe('Rate units: y, m, w, d, or h'),
  queued: z.boolean().optional().describe('Whether the graph is waiting to update'),
  frozen: z
    .boolean()
    .optional()
    .describe('Whether the goal must be restarted before accepting data'),
  lost: z.boolean().optional().describe('Whether the goal is off track'),
  graphUrl: z.string().optional().describe('Goal graph image URL'),
  svgUrl: z.string().optional().describe('Goal graph SVG URL'),
  thumbUrl: z.string().optional().describe('Goal thumbnail URL'),
  datapoints: z.array(z.unknown()).optional().describe('Datapoints when requested'),
  refreshQueued: z
    .boolean()
    .optional()
    .describe('Whether a requested graph refresh was queued'),
  raw: z.unknown().optional().describe('Complete provider goal response')
});

export let datapointSchema = z.object({
  datapointId: z.string().describe('Unique identifier for the datapoint'),
  timestamp: z.number().describe('Unix timestamp of the datapoint'),
  daystamp: z.string().describe('Date stamp in YYYYMMDD format'),
  value: z.number().describe('Numeric value of the datapoint'),
  comment: z.string().optional().describe('Optional comment on the datapoint'),
  requestid: z
    .string()
    .nullable()
    .optional()
    .describe('Client-provided unique ID for idempotent upserts'),
  updatedAt: z.number().optional().describe('Unix timestamp of last update'),
  goalSlug: z.string().optional().describe('Slug of the parent goal'),
  origin: z.string().optional().describe('Source that created the datapoint'),
  creator: z
    .string()
    .nullable()
    .optional()
    .describe('User who created the datapoint, when available'),
  isDummy: z.boolean().optional().describe('Whether the datapoint was generated by Beeminder'),
  isInitial: z.boolean().optional().describe('Whether this is the initial datapoint'),
  raw: z.unknown().optional().describe('Complete provider datapoint response')
});

export let userSchema = z.object({
  username: z.string().describe('Beeminder username'),
  timezone: z.string().optional().describe('User timezone'),
  updatedAt: z.number().optional().describe('Unix timestamp of last update'),
  deadbeat: z.boolean().optional().describe('Whether the user has failed to pay'),
  urgencyLoad: z.number().optional().describe('Total urgency across all goals'),
  hasAuthorizedSources: z
    .boolean()
    .optional()
    .describe('Whether user has authorized third-party sources'),
  goals: z.array(z.unknown()).optional().describe('Goal slugs or associated goal objects'),
  deletedGoals: z
    .array(z.unknown())
    .optional()
    .describe('Deleted goal identifiers when using diffSince'),
  raw: z.unknown().optional().describe('Complete provider user response')
});

export let chargeSchema = z.object({
  chargeId: z.string().optional().describe('Unique identifier for the charge'),
  amount: z.number().describe('Charge amount in USD'),
  note: z.string().optional().describe('Note attached to the charge'),
  userId: z.string().describe('Username of the charged user'),
  raw: z.unknown().optional().describe('Complete provider charge response')
});

export let responseRecord = (raw: unknown): Record<string, unknown> => {
  if (!isApiErrorRecord(raw)) {
    throw createApiServiceError('Beeminder returned an invalid object response.', {
      reason: 'beeminder_invalid_response'
    });
  }
  return raw;
};

export let responseArray = (raw: unknown): unknown[] => {
  if (!Array.isArray(raw)) {
    throw createApiServiceError('Beeminder returned an invalid list response.', {
      reason: 'beeminder_invalid_response'
    });
  }
  return raw;
};

let validated = <T>(schema: z.ZodType<T>, value: unknown): T => {
  let result = schema.safeParse(value);
  if (!result.success) {
    throw createApiServiceError(
      `Beeminder returned incomplete or invalid data: ${result.error.issues.map(issue => issue.path.join('.')).join(', ')}.`,
      { reason: 'beeminder_invalid_response' }
    );
  }
  return result.data;
};

let requiredText = (value: unknown, field: string) => {
  if (typeof value !== 'string' || !value.trim()) {
    throw createApiServiceError(`Beeminder did not return a valid ${field}.`, {
      reason: 'beeminder_invalid_response'
    });
  }
  return value;
};

let optional = (value: unknown) => (value === null ? undefined : value);

export let mapGoal = (value: unknown) => {
  let raw = responseRecord(value);
  return validated(goalSchema, {
    slug: requiredText(raw.slug, 'slug'),
    title: requiredText(raw.title, 'title'),
    goalType: requiredText(raw.goal_type, 'goalType'),
    gunits: requiredText(raw.gunits, 'gunits'),
    goaldate: raw.goaldate,
    goalval: raw.goalval,
    rate: raw.rate,
    curval: optional(raw.curval),
    curday: optional(raw.curday),
    pledge: optional(raw.pledge),
    yaxis: optional(raw.yaxis),
    safebuf: optional(raw.safebuf),
    safesum: optional(raw.safesum),
    losedate: optional(raw.losedate),
    limsum: optional(raw.limsum),
    deadline: optional(raw.deadline),
    secret: optional(raw.secret),
    datapublic: optional(raw.datapublic),
    tags: optional(raw.tags),
    updatedAt: optional(raw.updated_at),
    burner: optional(raw.burner),
    roadall: optional(raw.roadall),
    callbackUrl: raw.callback_url,
    autodata: raw.autodata,
    won: optional(raw.won),
    lane: optional(raw.lane),
    mathishard: optional(raw.mathishard),
    headsum: optional(raw.headsum),
    lastDatapoint: raw.last_datapoint,
    integery: optional(raw.integery),
    fineprint: raw.fineprint,
    todayta: optional(raw.todayta),
    hhmmformat: optional(raw.hhmmformat),
    id: optional(raw.id),
    runits: optional(raw.runits),
    queued: optional(raw.queued),
    frozen: optional(raw.frozen),
    lost: optional(raw.lost),
    graphUrl: optional(raw.graph_url),
    svgUrl: optional(raw.svg_url),
    thumbUrl: optional(raw.thumb_url),
    datapoints: optional(raw.datapoints),
    raw
  });
};

export let mapDatapoint = (value: unknown) => {
  let raw = responseRecord(value);
  return validated(datapointSchema, {
    datapointId: requiredText(raw.id, 'datapointId'),
    timestamp: raw.timestamp,
    daystamp: requiredText(raw.daystamp, 'daystamp'),
    value: raw.value,
    comment: optional(raw.comment),
    requestid: raw.requestid,
    updatedAt: optional(raw.updated_at),
    goalSlug: optional(raw.goal_slug),
    origin: optional(raw.origin),
    creator: raw.creator,
    isDummy: optional(raw.is_dummy),
    isInitial: optional(raw.is_initial),
    raw
  });
};

export let mapUser = (value: unknown) => {
  let raw = responseRecord(value);
  return validated(userSchema, {
    username: requiredText(raw.username, 'username'),
    timezone: optional(raw.timezone),
    updatedAt: optional(raw.updated_at),
    deadbeat: optional(raw.deadbeat),
    urgencyLoad: optional(raw.urgency_load),
    hasAuthorizedSources: optional(raw.has_authorized_sources),
    goals: optional(raw.goals),
    deletedGoals: optional(raw.deleted_goals),
    raw
  });
};

export let mapCharge = (value: unknown) => {
  let raw = responseRecord(value);
  return validated(chargeSchema, {
    chargeId: optional(raw.id),
    amount: raw.amount,
    note: optional(raw.note),
    userId: requiredText(raw.username ?? raw.user_id, 'charged username'),
    raw
  });
};
