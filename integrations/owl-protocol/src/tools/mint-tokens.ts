import { createApiServiceError, SlateTool } from 'slates';
import { z } from 'zod';
import {
  mintTimeoutGuidance,
  OwlClient,
  owlObject,
  owlRecords,
  requireChainId,
  requireInput,
  requireOwlString
} from '../lib/client';
import { rawSchema } from '../lib/schemas';
import { spec } from '../spec';

export let mintTokens = SlateTool.create(spec, {
  name: 'Mint ERC721 Tokens',
  key: 'mint_tokens',
  description: `Mint one or more ERC721 tokens (NFTs) from a deployed collection to specified recipients.
Recipients can be email addresses, user IDs, or Ethereum wallet addresses.
Token IDs are auto-generated by the contract.
Supports both inline metadata and template-based minting.`,
  instructions: [
    'Provide at most one of metadata or templateId; both may be omitted.',
    'Recipients can be email addresses (for project users), user IDs, or Ethereum addresses.',
    'The collection must already be deployed before minting.',
    mintTimeoutGuidance
  ],
  tags: {
    destructive: false,
    readOnly: false
  }
})
  .input(
    z.object({
      chainId: z.number().describe('Chain ID where the collection is deployed'),
      contractAddress: z
        .string()
        .describe('Contract address of the deployed ERC721 collection'),
      recipients: z
        .array(z.string())
        .describe('Array of recipients: email addresses, user IDs, or Ethereum addresses'),
      metadata: z
        .object({
          name: z.string().optional().describe('Token name'),
          description: z.string().optional().describe('Token description'),
          image: z.string().optional().describe('Token image URL or base64-encoded image'),
          attributes: z
            .array(
              z.object({
                trait_type: z.string().describe('Attribute name'),
                value: z.string().describe('Attribute value')
              })
            )
            .optional()
            .describe('Token attributes/traits')
        })
        .optional()
        .describe('Inline metadata for the minted tokens'),
      wait: z
        .boolean()
        .optional()
        .describe('Wait for execution before returning token details.'),
      templateId: z
        .string()
        .optional()
        .describe('ID of a previously created token template to use for metadata')
    })
  )
  .output(
    z.object({
      raw: rawSchema,
      wait: z.boolean().optional().describe('Whether the provider waited for execution.'),
      tokens: z
        .array(z.record(z.string(), z.unknown()))
        .optional()
        .describe('Array of minted token details including tokenId and recipient'),
      userOpHash: z
        .string()
        .optional()
        .describe('ERC4337 user operation hash for the mint operation'),
      metadata: z
        .record(z.string(), z.unknown())
        .optional()
        .describe('Metadata applied to the minted tokens')
    })
  )
  .handleInvocation(async ctx => {
    let client = new OwlClient({ token: ctx.auth.token });

    let chainId = requireChainId(ctx.input.chainId ?? ctx.config.chainId);
    requireInput(ctx.input.contractAddress, 'contractAddress');
    if (!ctx.input.recipients.length) {
      throw createApiServiceError('Provide at least one recipient.', {
        reason: 'owl_protocol_invalid_input'
      });
    }
    for (let recipient of ctx.input.recipients) requireInput(recipient, 'recipient');
    if (ctx.input.metadata !== undefined && ctx.input.templateId !== undefined) {
      throw createApiServiceError('Provide metadata or templateId, not both.', {
        reason: 'owl_protocol_invalid_input'
      });
    }
    if (ctx.input.templateId !== undefined) requireInput(ctx.input.templateId, 'templateId');

    ctx.info({
      message: 'Minting tokens',
      contractAddress: ctx.input.contractAddress,
      recipientCount: ctx.input.recipients.length,
      chainId
    });

    let result = await client.mintBatchERC721({
      chainId,
      contractAddress: ctx.input.contractAddress,
      to: ctx.input.recipients,
      metadata: ctx.input.metadata,
      projectTokenTemplateId: ctx.input.templateId,
      wait: ctx.input.wait
    });

    let tokens =
      result.tokens === undefined || result.tokens === null
        ? undefined
        : owlRecords(result.tokens, 'minted tokens');

    return {
      output: {
        raw: result,
        wait: typeof result.wait === 'boolean' ? result.wait : undefined,
        tokens,
        userOpHash: requireOwlString(result.userOpHash, 'mint user operation hash'),
        metadata: owlObject(result.metadata)
      },
      message: tokens
        ? `Owl Protocol returned **${tokens.length}** minted token(s) on chain ${chainId}.`
        : `Submitted a mint operation for ${ctx.input.recipients.length} recipient(s) on chain ${chainId}.`
    };
  })
  .build();
