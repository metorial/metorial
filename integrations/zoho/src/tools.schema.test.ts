describeMcpCompatibleToolSchemas('Zoho tool input schemas', provider.actions);
describe('Zoho consolidated tool contract', () => {
  const tools = provider.actions.filter(action => action.type === 'tool');
  const keys = tools.map(tool => tool.key);
  it('preserves all standalone capabilities and all existing Zoho tools', () => {
    expect(keys).toEqual(expect.arrayContaining([...importedKeys, ...originalKeys]));
  });
  it('has unique keys and production IDs below 60 characters', () => {
    expect(new Set(keys).size).toBe(keys.length);
    for (const key of keys) expect(`zoho-${key}`.length).toBeLessThan(60);
  });
  it('discovers organization and account IDs without required connection config', () => {
    expect(keys).toEqual(
      expect.arrayContaining([
        'who_am_i',
        'books_list_organizations',
        'invoice_list_organizations',
        'inventory_list_organizations',
        'desk_list_organizations',
        'mail_get_account_info'
      ])
    );
    expect(provider.spec.configSchema.parse({})).toEqual({});
  });
});
