import { SlateTool } from 'slates';
import { z } from 'zod';
import { Client } from '../lib/client';
import { spec } from '../spec';

export let listImages = SlateTool.create(spec, {
  name: 'List Images',
  key: 'list_images',
  description: `Retrieve a list of all images previously generated by your account. Returns one page of image metadata and the cursor for the next page. Legacy page numbers are resolved by following cursors from the first page.`,
  tags: {
    destructive: false,
    readOnly: true
  }
})
  .input(
    z.object({
      page: z.number().optional().describe('Page number for pagination'),
      perPage: z.number().optional().describe('Number of images per page (1-50)'),
      pageToken: z
        .string()
        .optional()
        .describe(
          'Use nextPageToken from the previous result to request the next page; omit for the first page'
        )
    })
  )
  .output(
    z.object({
      images: z
        .array(
          z.object({
            imageId: z.string().describe('Unique identifier for the image'),
            url: z.string().describe('Permanent CDN-cached URL of the image'),
            createdAt: z.string().describe('Timestamp when the image was created'),
            html: z.string().optional().describe('HTML markup used to generate the image'),
            css: z.string().optional().describe('CSS styling applied to the image'),
            googleFonts: z.string().optional().describe('Google Fonts used'),
            msDelay: z.number().optional().describe('Render delay in milliseconds'),
            deviceScale: z.number().optional().describe('Device scale factor'),
            selector: z.string().optional().describe('CSS selector used for cropping'),
            viewportWidth: z.number().optional().describe('Viewport width used'),
            viewportHeight: z.number().optional().describe('Viewport height used'),
            templateId: z
              .string()
              .optional()
              .describe('Template ID if generated from a template'),
            templateVersion: z.number().optional().describe('Template version used'),
            raw: z
              .record(z.string(), z.unknown())
              .describe('Original image metadata with credentials removed')
          })
        )
        .describe('List of generated images'),
      nextPageToken: z
        .string()
        .nullable()
        .optional()
        .describe('Cursor for the next page when supplied by the provider'),
      hasNextPage: z
        .boolean()
        .optional()
        .describe('Whether the provider reports another page'),
      raw: z
        .record(z.string(), z.unknown())
        .describe('Provider list response with credentials removed')
    })
  )
  .handleInvocation(async ctx => {
    let client = new Client({
      userId: ctx.auth.userId,
      token: ctx.auth.token
    });

    let result = await client.listImages(
      ctx.input.page,
      ctx.input.perPage,
      ctx.input.pageToken
    );

    return {
      output: result,
      message: `Retrieved **${result.images.length}** image(s).`
    };
  })
  .build();
